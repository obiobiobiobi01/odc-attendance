import assert from 'node:assert/strict';
import {monthRange,dayLabel,calculate,totals,duration,csv} from '../public/attendance-report.js';
const ts=s=>({toMillis:()=>Date.parse(s)});
const r={clockIn:ts('2026-10-15T12:22:31+09:00'),clockOut:ts('2026-10-15T16:33:56+09:00')};
assert.equal(duration(calculate(r).gross),'4:11:25');
assert.equal(calculate(r).net,null);
assert.equal(duration(calculate(r,{breakMinutes:60}).net),'3:11:25');
assert.equal(duration(calculate(r,{breakMinutes:0}).net),'4:11:25');
for(const breakMinutes of [-1,252,0.5,'60'])assert.equal(calculate(r,{breakMinutes}).net,null);
assert.equal(calculate({...r,clockOut:null},{breakMinutes:0}).net,null);
const overnight={clockIn:ts('2026-10-31T22:00:00+09:00'),clockOut:ts('2026-11-01T06:00:00+09:00')};
assert.equal(duration(calculate(overnight,{breakMinutes:60}).net),'7:00:00');
assert.equal(dayLabel(monthRange('2026-10')[0]),'2026-10-01');
assert.equal(dayLabel(monthRange('2026-10')[1]),'2026-11-01');
assert.equal(monthRange('2028-02')[1]-monthRange('2028-02')[0],29);
for(const m of ['2026-13','2026-00','bad','0099-01'])assert.throws(()=>monthRange(m));
const sum=totals([calculate(r,{breakMinutes:60}),calculate(r),calculate({...r,clockOut:null})]);
assert.equal(sum.pending,2);assert.equal(sum.confirmed,1);assert.equal(duration(sum.net),'3:11:25');
assert.equal(duration(100*3600000),'100:00:00');
assert.equal(csv([['=cmd','a"b','x,y','\n@sum']]),'"\'=cmd","a""b","x,y","\'\n@sum"');
console.log('PASS report: exact seconds, confirmed-only sums, rest validation, overnight, leap month, CSV quoting');
