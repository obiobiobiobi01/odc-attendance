import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFileSync} from 'node:fs';
import {initializeApp} from 'firebase-admin/app';
import {getFirestore,Timestamp} from 'firebase-admin/firestore';
import {initializeTestEnvironment,assertFails} from '@firebase/rules-unit-testing';
import {doc,setDoc,serverTimestamp} from 'firebase/firestore';
const require=createRequire(import.meta.url),{clinicNetwork,handlePunch}=require('../functions/punch.js');
const allowed='203.0.113.10';
assert.equal(clinicNetwork(allowed,allowed),true);
for(const h of [undefined,'','198.51.100.1',`${allowed}, 198.51.100.1`,`198.51.100.1, ${allowed}`,'::1'])assert.equal(clinicNetwork(h,allowed),false);
const projectId='demo-clinic';
const env=await initializeTestEnvironment({projectId,firestore:{host:'127.0.0.1',port:8080,rules:readFileSync(new URL('../firestore.rules',import.meta.url),'utf8')}});
initializeApp({projectId});const db=getFirestore();
const claims={email:'a@example.com',email_verified:true,firebase:{sign_in_provider:'google.com'}};
const auth={uid:'a',token:claims};
const call=(data,extra={})=>handlePunch({db,auth,data,header:allowed,allowed,Timestamp,fail:(code,message)=>Object.assign(new Error(message),{code}),...extra});
try{
 await env.clearFirestore();await db.doc('settings/clinic').set({emails:['a@example.com']});
 assert.deepEqual(await call({kind:'check'}),{allowed:true});
 assert.deepEqual(await call({kind:'check'},{header:'198.51.100.1'}),{allowed:false});
 await assert.rejects(call({kind:'in'},{auth:null}),{code:'unauthenticated'});
 await assert.rejects(call({kind:'in'},{auth:{uid:'b',token:{...claims,email:'b@example.com'}}}),{code:'permission-denied'});
 await assert.rejects(call({kind:'in'},{header:'198.51.100.1'}),{code:'permission-denied'});
 await assert.rejects(call({kind:'in',uid:'b'}),{code:'invalid-argument'});
 const raced=await Promise.allSettled([call({kind:'in'}),call({kind:'in'})]);
 assert.equal(raced.filter(r=>r.status==='fulfilled').length,1);
 const before=(await db.doc('attendance/a').get()).data();
 assert.equal(before.clockOut,null);
 await assert.rejects(call({kind:'out'},{header:'198.51.100.1'}),{code:'permission-denied'});
 await call({kind:'out'});
 const after=(await db.doc('attendance/a').get()).data();assert.ok(after.clockOut.toMillis()>=after.clockIn.toMillis());
 assert.deepEqual((await db.doc(`attendance/a/days/${after.day}`).get()).data(),after);
 await assert.rejects(call({kind:'out'}),{code:'failed-precondition'});
 await assert.rejects(call({kind:'in'}),{code:'failed-precondition'});
 const client=env.authenticatedContext('a',claims).firestore();
 await assertFails(setDoc(doc(client,'attendance','a'),{day:after.day+1,clockIn:serverTimestamp(),clockOut:null}));
 await assertFails(setDoc(doc(client,'attendance','a','days',String(after.day+1)),{day:after.day+1,clockIn:serverTimestamp(),clockOut:null}));
 console.log('PASS: clinic network, spoofed headers denied, authentication, registration, concurrent punching, duplicate prevention, atomic history, direct client writes denied');
}finally{await env.cleanup();await db.terminate();}
